const qs = (selector, scope = document) => scope.querySelector(selector);
const qsa = (selector, scope = document) => [...scope.querySelectorAll(selector)];

function blockMarkup([heading, content]) {
  const body = Array.isArray(content)
    ? `<ul>${content.map((item) => `<li>${item}</li>`).join("")}</ul>`
    : `<p>${content}</p>`;

  return `<div class="modal-block"><h3>${heading}</h3>${body}</div>`;
}

function openModal(key) {
  const data = modalData[key];
  const overlay = qs("#modalOverlay");
  const modal = qs("#modalContent");
  const body = qs("#modalBody");
  const close = qs("#modalClose");

  if (!data || !overlay || !modal || !body) return;

  body.innerHTML = `
    <p class="modal-eyebrow">${data.eyebrow}</p>
    <h2>${data.title}</h2>
    <p class="modal-description">${data.description}</p>
    ${data.blocks.map(blockMarkup).join("")}
    ${data.price ? `<div class="modal-price-box"><p class="modal-eyebrow">Rango de inversi&oacute;n</p><p><strong>${data.price}</strong></p></div>` : ""}
  `;

  overlay.classList.add("active");
  document.body.classList.add("modal-open");
  overlay.scrollTop = 0;
  modal.scrollTop = 0;
  close?.focus();
}

function closeModal() {
  qs("#modalOverlay")?.classList.remove("active");
  document.body.classList.remove("modal-open");
}

function initMenu() {
  const toggle = qs(".menu-toggle");
  const links = qs(".nav-links");
  if (!toggle || !links) return;

  toggle.setAttribute("aria-label", "Abrir menu");
  toggle.setAttribute("aria-expanded", "false");

  toggle.addEventListener("click", () => {
    const open = !links.classList.contains("active");
    links.classList.toggle("active", open);
    toggle.setAttribute("aria-expanded", String(open));
  });

  qsa(".nav-links a").forEach((link) => {
    link.addEventListener("click", () => {
      links.classList.remove("active");
      toggle.setAttribute("aria-expanded", "false");
    });
  });
}

function initModals() {
  qsa("[data-modal]").forEach((button) => {
    button.addEventListener("click", () => openModal(button.dataset.modal));
  });

  qs("#modalClose")?.addEventListener("click", closeModal);
  qs("#modalOverlay")?.addEventListener("click", (event) => {
    if (event.target.id === "modalOverlay") closeModal();
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeModal();
  });
}

document.addEventListener("DOMContentLoaded", () => {
  initMenu();
  initModals();
});
